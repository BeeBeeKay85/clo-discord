create table if not exists clo_messages (
  id bigint generated by default as identity primary key,
  channel_id text not null,
  role text not null check (role in ('user','assistant')),
  content text not null,
  created_at timestamptz not null default now()
);
create index if not exists clo_messages_channel_created_idx on clo_messages(channel_id,created_at desc);

create table if not exists clo_memories (
  id bigint generated by default as identity primary key,
  content text not null,
  category text default 'otro',
  importance integer default 5 check (importance between 1 and 10),
  era text default 'desconocida',
  event_date date,
  keywords text[] default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists clo_memories_importance_idx on clo_memories(importance desc,created_at desc);

create table if not exists clo_activity (
  channel_id text primary key,
  last_user_message_at timestamptz,
  last_bot_initiated_at timestamptz,
  updated_at timestamptz not null default now()
);

alter table clo_messages enable row level security;
alter table clo_memories enable row level security;
alter table clo_activity enable row level security;

